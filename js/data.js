function fmt(n, decimals) {
  if (n === undefined || n === null || isNaN(n)) return '0';
  const d = decimals === undefined ? 2 : decimals;
  return Number(n).toLocaleString('es-VE', { minimumFractionDigits: d, maximumFractionDigits: d });
}

